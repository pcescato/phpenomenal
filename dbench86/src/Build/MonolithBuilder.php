<?php
declare(strict_types=1);

namespace DBench86\Build;

/** Core-only packaging of the canonical classes, with inheritance dependencies first. */
final class MonolithBuilder
{
    public function __construct(private readonly string $projectDirectory) {}

    /** @return list<string> Project-relative source paths in deterministic build order. */
    public function sourceFiles(): array
    {
        $files = [];
        $directory = $this->projectDirectory . '/src';
        if (!is_dir($directory)) {
            throw new \RuntimeException('Building requires the canonical DBench86 src/ tree.');
        }
        foreach (new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($directory)) as $file) {
            if ($file->isFile() && $file->getExtension() === 'php') {
                $relative = substr($file->getPathname(), strlen($this->projectDirectory) + 1);
                $class = 'DBench86\\' . str_replace('/', '\\', substr($relative, 4, -4));
                $files[$class] = $relative;
            }
        }
        asort($files, SORT_STRING);
        $ordered = [];
        $visiting = [];
        $visit = function (string $class) use (&$visit, &$ordered, &$visiting, $files): void {
            if (isset($ordered[$class])) { return; }
            if (isset($visiting[$class])) {
                throw new \RuntimeException('Cyclic source dependency: ' . $class);
            }
            $visiting[$class] = true;
            // Reflection uses the normal production autoloader, never a second class parser.
            $reflection = new \ReflectionClass($class);
            if (realpath($reflection->getFileName()) !== realpath($this->projectDirectory . '/' . $files[$class])) {
                throw new \RuntimeException('Loaded class is not from the canonical source: ' . $class);
            }
            $dependencies = $reflection->getInterfaceNames();
            if ($parent = $reflection->getParentClass()) {
                $dependencies[] = $parent->getName();
            }
            sort($dependencies, SORT_STRING);
            foreach ($dependencies as $dependency) {
                if (isset($files[$dependency])) { $visit($dependency); }
            }
            unset($visiting[$class]);
            $ordered[$class] = $files[$class];
        };
        foreach (array_keys($files) as $class) { $visit($class); }
        return array_values($ordered);
    }

    public function build(): string
    {
        $output = "<?php\ndeclare(strict_types=1);\n\n"
            . "// Generated by DBench86 from canonical multi-file sources.\n"
            . "// Do not edit this file directly.\n";
        foreach ($this->sourceFiles() as $relative) {
            $output .= "\n// Source: {$relative}\n" . $this->namespaceBlock(file_get_contents($this->projectDirectory . '/' . $relative));
        }
        // Environment and CLI dispatch are the same production components as the launcher.
        $output .= <<<'PHP_SOURCE'

namespace {
    \DBench86\Configuration\Environment::load(__DIR__);
    exit(\DBench86\Cli\Launcher::run($argv, __DIR__));
}
PHP_SOURCE;
        return $output . "\n";
    }

    public function write(string $path): void
    {
        $source = $this->build();
        $directory = dirname($path);
        if (!is_dir($directory) && !mkdir($directory, 0777, true) && !is_dir($directory)) {
            throw new \RuntimeException('Cannot create build output directory.');
        }
        if (file_put_contents($path, $source) !== strlen($source)) {
            throw new \RuntimeException('Cannot write monolithic build.');
        }
    }

    /** Preserve all implementation tokens; only normalize the file-level envelope. */
    private function namespaceBlock(string $source): string
    {
        $tokens = \PhpToken::tokenize($source);
        $output = '';
        $namespaces = 0;
        for ($i = 0; $i < count($tokens); $i++) {
            $token = $tokens[$i];
            if ($token->is(T_OPEN_TAG)) { continue; }
            if ($token->is(T_DECLARE)) {
                $declaration = '';
                do { $declaration .= $tokens[$i]->text; } while ($tokens[$i++]->text !== ';');
                $i--;
                if (preg_replace('/\s+/', '', $declaration) !== 'declare(strict_types=1);') {
                    throw new \RuntimeException('Unsupported source declaration.');
                }
                continue;
            }
            if ($token->is(T_NAMESPACE)) {
                if (++$namespaces !== 1) { throw new \RuntimeException('Expected one namespace per source file.'); }
                do {
                    $output .= $tokens[$i]->text === ';' ? '{' : $tokens[$i]->text;
                } while ($tokens[$i++]->text !== ';');
                $i--;
                continue;
            }
            if ($token->is([T_CLOSE_TAG, T_INLINE_HTML, T_REQUIRE, T_REQUIRE_ONCE, T_INCLUDE, T_INCLUDE_ONCE, T_DIR, T_FILE])) {
                throw new \RuntimeException('Source requires explicit packaging support for: ' . $token->text);
            }
            $output .= $token->text;
        }
        if ($namespaces !== 1) { throw new \RuntimeException('Expected a namespaced production source.'); }
        return trim($output) . "\n}\n";
    }
}
