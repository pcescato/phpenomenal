<?php
declare(strict_types=1);

namespace Tests\Unit;

use DBench86\Build\MonolithBuilder;
use Tests\TestCase;

final class MonolithBuildTest extends TestCase
{
    public function run(): void
    {
        $root = dirname(__DIR__, 2);
        $builder = new MonolithBuilder($root);
        $first = $builder->build();
        $this->assertEquals($first, $builder->build(), 'Identical sources produce byte-identical executable builds');
        $this->assertTrue(str_contains($first, 'Do not edit this file directly.'));
        $this->assertTrue(!str_contains($first, '/root/') && !str_contains($first, '/home/ubuntu/'), 'No absolute machine paths');
        $this->assertTrue(!str_contains($first, "require __DIR__") && !str_contains($first, 'spl_autoload_register'), 'No source-tree runtime loader');
        $sources = $builder->sourceFiles();
        $found = [];
        foreach (new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($root . '/src')) as $file) {
            if ($file->isFile() && $file->getExtension() === 'php') {
                $found[] = substr($file->getPathname(), strlen($root) + 1);
            }
        }
        $sorted = $sources;
        sort($sorted);
        sort($found);
        $this->assertEquals($found, $sorted, 'Every canonical production PHP source included exactly once');
        foreach ($sources as $source) {
            $this->assertEquals(1, substr_count($first, '// Source: ' . $source . "\n"));
        }

        $directory = sys_get_temp_dir() . '/dbench86-standalone-' . bin2hex(random_bytes(8));
        mkdir($directory);
        $path = $directory . '/dbench86-monolith.php';
        try {
            $builder->write($path);
            $hash = hash_file('sha256', $path);
            $builder->write($path);
            $this->assertEquals($hash, hash_file('sha256', $path), 'Written build SHA-256 reproducibility');
            $this->assertEquals(['.', '..', 'dbench86-monolith.php'], scandir($directory), 'Isolated directory contains only monolith');
            [$code, $lint, $error] = $this->execute(['-l', $path], $directory);
            $this->assertEquals(0, $code, $lint . $error);
            $this->assertTrue(str_contains($lint, 'No syntax errors'));
            [$code, $help, $error] = $this->execute([$path, '--help'], $directory);
            $this->assertEquals(0, $code, $error);
            $this->assertTrue(str_contains($help, '--database') && str_contains($help, '--build-monolith'));
            [$code, $normalHelp, $error] = $this->execute([$root . '/dbench86.php', '--help'], $directory);
            $this->assertEquals(0, $code, $error);
            $this->assertEquals($normalHelp, $help, 'Shared CLI help behavior');

            $arguments = ['--database=sqlite', '--rows=1000', '--runs=3', '--warmup=1', '--timeout=30'];
            [$code, $monoOutput, $error] = $this->execute([$path, ...$arguments], $directory);
            $this->assertEquals(0, $code, $monoOutput . $error);
            [$code, $normalOutput, $error] = $this->execute([$root . '/dbench86.php', ...$arguments], $directory);
            $this->assertEquals(0, $code, $normalOutput . $error);
            $this->assertEquals($this->semanticOutput($normalOutput), $this->semanticOutput($monoOutput), 'Same deterministic output and per-workload accounting; latency order and memory usage may differ');
            $this->assertEquals(10, substr_count($monoOutput, '3/3'), 'All ten workloads complete all requested measured runs');
            $this->assertTrue(str_contains($monoOutput, 'Warmup: all workloads completed successfully (1/1).'));
            $this->assertTrue(str_contains($monoOutput, 'Batch size: 100 rows') && str_contains($monoOutput, 'Dataset populated: 1000 rows'));
            $this->assertTrue(!str_contains($monoOutput, '[FAILED]') && !str_contains($monoOutput, 'Warmup issues:'));

            [$code, $output, $error] = $this->execute([$root . '/dbench86.php', '--build-monolith'], $directory);
            $this->assertEquals(0, $code, $error);
            $this->assertEquals("Built dist/dbench86-monolith.php\n", $output, 'Build mode produces no benchmark output');
            $this->assertEquals($first, file_get_contents($root . '/dist/dbench86-monolith.php'), 'CLI and test builder are identical');
            [$code, $output, $error] = $this->execute([$root . '/dbench86.php', '--build-monolith', '--database=sqlite'], $directory);
            $this->assertTrue($code !== 0 && str_contains($error, 'must be used alone') && $output === '', 'Build and benchmark modes cannot be mixed');
            [$code, $output, $error] = $this->execute([$path, '--build-monolith'], $directory);
            $this->assertTrue($code !== 0 && str_contains($error, 'canonical DBench86 src/ tree') && $output === '', 'Standalone runtime never resolves source files for rebuilding');
        } finally {
            unlink($path);
            rmdir($directory);
        }
    }

    private function execute(array $arguments, string $directory): array
    {
        $process = proc_open([PHP_BINARY, ...$arguments], [0 => ['file', '/dev/null', 'r'], 1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes, $directory);
        if (!is_resource($process)) { throw new \RuntimeException('Cannot start PHP subprocess.'); }
        $output = stream_get_contents($pipes[1]);
        $error = stream_get_contents($pipes[2]);
        fclose($pipes[1]);
        fclose($pipes[2]);
        return [proc_close($process), $output, $error];
    }

    private function semanticOutput(string $output): array
    {
        $lines = [];
        $rows = [];
        foreach (explode("\n", $output) as $line) {
            if (preg_match('/^(\w+)\s+(\d+\/\d+)\s+\d+\.\d{3}\s+\d+\.\d{3}\s+\d+\.\d{3}\s+\d+\.\d{3}$/', $line, $match)) {
                $rows[$match[1]] = $match[2];
            } elseif (!preg_match('/^  (?:usage|peak usage):/', $line)) {
                $lines[] = $line;
            }
        }
        ksort($rows);
        return [$lines, $rows];
    }
}

(new MonolithBuildTest())->run();
